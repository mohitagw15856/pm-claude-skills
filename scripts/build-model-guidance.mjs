#!/usr/bin/env node
// Per-skill model and effort guidance: which role in data/models.json to start
// a skill on, and at what effort. Written to data/model-guidance.json and
// docs/MODEL-GUIDANCE.md, and read by `pm-claude-skills run <skill> --auto-model`.
//
// The guidance is derived, not measured: it follows from the risk tier
// (data/risk-tiers.json), the length of the skill and whether it reads images.
// It is a starting point that costs nothing to compute. SkillBench is the way
// to measure it; an entry in data/model-guidance-overrides.json records a
// measured or reasoned exception and wins over the rules.
//
//   node scripts/build-model-guidance.mjs           write both files
//   node scripts/build-model-guidance.mjs --check   exit 1 if either file is stale
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { REGISTRY, modelFor, modelInfo } from '../bin/lib/models.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const tiers = JSON.parse(read('data/risk-tiers.json')).tiers;
const overridesFile = 'data/model-guidance-overrides.json';
const overrides = existsSync(join(ROOT, overridesFile)) ? JSON.parse(read(overridesFile)).skills || {} : {};

const SHORT = 600;   // words: a skill this short asks for a bounded, mostly mechanical output
const LONG = 2200;   // words: a method this long needs the model to hold many rules at once
const VISION = /\b(screenshot|image of|photo of|scanned|chart image|pixel)/i;

const RULES = {
  'high-stakes': { role: 'deep', effort: 'high', why: 'High-stakes tier: a wrong figure or a missed clause costs the reader money or a legal position.' },
  consequential: { role: 'default', effort: 'high', why: 'Consequential tier: the output is acted on, so spend effort on the checks rather than on a larger model.' },
  long: { role: 'default', effort: 'high', why: 'Long method: many rules to hold at once.' },
  vision: { role: 'default', effort: 'medium', why: 'Reads images: the smallest model loses detail on dense screenshots and charts.' },
  short: { role: 'fast', effort: 'low', why: 'Informational tier and a short, bounded method: the smallest model follows it, at a twentieth of the price.' },
  base: { role: 'default', effort: 'medium', why: 'Informational tier: the default model at its normal effort.' },
};

const skills = {};
for (const name of readdirSync(join(ROOT, 'skills')).sort()) {
  const file = join(ROOT, 'skills', name, 'SKILL.md');
  if (!existsSync(file)) continue;
  const text = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  const body = text.replace(/^---\n[\s\S]*?\n---\n/, '');
  const words = body.split(/\s+/).filter(Boolean).length;
  const tier = (tiers[name] && tiers[name].tier) || 'informational';
  let rule;
  if (tier === 'high-stakes') rule = 'high-stakes';
  else if (tier === 'consequential') rule = 'consequential';
  else if (VISION.test(body)) rule = 'vision';
  else if (words >= LONG) rule = 'long';
  else if (words <= SHORT) rule = 'short';
  else rule = 'base';
  const o = overrides[name];
  skills[name] = o ? { role: o.role, effort: o.effort, rule: 'override', why: o.why } : { role: RULES[rule].role, effort: RULES[rule].effort, rule };
}
for (const name of Object.keys(overrides)) {
  if (!skills[name]) { console.error(`✗ ${overridesFile}: "${name}" is not a skill`); process.exit(1); }
  const o = overrides[name];
  if (!(o.role in REGISTRY.roles) || o.role === 'judge') { console.error(`✗ ${overridesFile}: ${name}: role "${o.role}" is not a usable role`); process.exit(1); }
  if (!['low', 'medium', 'high', 'xhigh', 'max'].includes(o.effort)) { console.error(`✗ ${overridesFile}: ${name}: effort "${o.effort}"`); process.exit(1); }
  if (!o.why) { console.error(`✗ ${overridesFile}: ${name}: say why`); process.exit(1); }
}

const data = {
  _comment: 'Generated by scripts/build-model-guidance.mjs. Derived from the risk tier, length and image use of each skill; not measured. Edit data/model-guidance-overrides.json, not this file.',
  rules: Object.fromEntries(Object.entries(RULES).map(([k, v]) => [k, v])),
  skills,
};
const json = JSON.stringify(data, null, 1) + '\n';

const count = {};
for (const s of Object.values(skills)) { const k = `${s.role}|${s.effort}`; count[k] = (count[k] || 0) + 1; }
const total = Object.keys(skills).length;
const price = (role) => { const i = modelInfo(modelFor(role)); return `$${i.input} in, $${i.output} out`; };
const rows = Object.entries(count).sort((a, b) => b[1] - a[1]).map(([k, n]) => {
  const [role, effort] = k.split('|');
  return `| ${role} | \`${modelFor(role)}\` | ${effort} | ${n.toLocaleString('en-GB')} | ${price(role)} |`;
});
const ruleRows = Object.entries(RULES).map(([k, v]) => {
  const n = Object.values(skills).filter((s) => s.rule === k).length;
  return `| ${k} | ${v.role} | ${v.effort} | ${n.toLocaleString('en-GB')} | ${v.why} |`;
});
const overrideRows = Object.entries(overrides).map(([n, o]) => `| \`${n}\` | ${o.role} | ${o.effort} | ${o.why} |`);
const md = `# Which model and effort for which skill

<!-- Generated by scripts/build-model-guidance.mjs. Do not edit by hand. -->

Every skill runs on every current model. This page says where to **start**: the cheapest model and effort that the skill's stakes and length justify. The data is in [data/model-guidance.json](../data/model-guidance.json), one entry per skill, for ${total.toLocaleString('en-GB')} skills.

**This guidance is derived, not measured.** It follows from three facts about each skill: its risk tier, how long its method is, and whether it reads images. Nothing here was scored against model output, because scoring costs API credit. [SkillBench](../skillbench/README.md) is the way to measure it (\`node skillbench/run-skillbench.mjs --lineup current --dry-run\` shows the plan and the price first).

## Use it

\`\`\`bash
npx pm-claude-skills run contract-review --input contract.txt --auto-model
\`\`\`

\`--auto-model\` picks the model and effort from this table. Without it, \`run\` uses the default role, as before. \`--model\` always wins.

## The spread

| Role | Model today | Effort | Skills | Price per million tokens |
|---|---|---|---|---|
${rows.join('\n')}

Roles resolve through [data/models.json](../data/models.json), so when a model is replaced this table moves with it. See [MODELS.md](MODELS.md).

## The rules, in order

| Rule | Role | Effort | Skills | Why |
|---|---|---|---|---|
${ruleRows.join('\n')}

A skill takes the first rule that matches: high-stakes, consequential, reads images, long (${LONG.toLocaleString('en-GB')} words or more), short (${SHORT} words or fewer), otherwise the base rule. The risk tiers come from [data/risk-tiers.json](../data/risk-tiers.json).

Three things the rules do on purpose:

- **Stakes buy effort before they buy a larger model.** A consequential skill stays on the default model at high effort. Only the high-stakes tier moves up a model.
- **No skill starts on the frontier model.** A single skill is one bounded document. The frontier role is for [missions](MISSIONS.md), where one run holds seven to ten steps together.
- **The smallest model is offered only where little can go wrong:** informational tier and a short method.

## Overrides

${overrideRows.length ? `| Skill | Role | Effort | Why |\n|---|---|---|---|\n${overrideRows.join('\n')}` : 'None yet.'}

Add an entry to [data/model-guidance-overrides.json](../data/model-guidance-overrides.json) when a measurement or a clear reason disagrees with the rules, then rerun the generator. Each override must say why.

## What effort means

Effort is how much the model thinks before it answers. On the current models thinking is on by default and shares the output limit, so the client adds headroom for it (see [MODELS.md](MODELS.md)). Low effort is faster and cheaper; high effort checks more of its own work. If a skill's output misses its own quality checks, raise effort first, and change model second.
`;

const jsonPath = join(ROOT, 'data', 'model-guidance.json');
const mdPath = join(ROOT, 'docs', 'MODEL-GUIDANCE.md');
if (check) {
  const stale = [];
  if (!existsSync(jsonPath) || readFileSync(jsonPath, 'utf8') !== json) stale.push('data/model-guidance.json');
  if (!existsSync(mdPath) || readFileSync(mdPath, 'utf8') !== md) stale.push('docs/MODEL-GUIDANCE.md');
  if (stale.length) { console.error(`✗ model guidance is stale: ${stale.join(', ')}. Run: node scripts/build-model-guidance.mjs`); process.exit(1); }
  console.log(`model guidance: ${total} skills, up to date ✓`);
} else {
  writeFileSync(jsonPath, json);
  writeFileSync(mdPath, md);
  console.log(`model guidance: ${total} skills`);
  for (const [k, n] of Object.entries(count).sort((a, b) => b[1] - a[1])) console.log(`  ${String(n).padStart(5)}  ${k.replace('|', ', effort ')}`);
}
