#!/usr/bin/env node
// Exports the Simplified Chinese skills as LobeHub agents, ready to upload to the
// agent market at app.lobehub.com (the lobe-chat-agents repo no longer takes pull
// requests; its maintainers ask for uploads through the app instead).
//
// One JSON file per skill in LobeHub's agent format (schemaVersion 1, the same
// shape as the files in lobehub/lobe-chat-agents/src): the skill body becomes the
// system role, the "示例触发语" become the opening questions. Plus index.json.
//
//   node scripts/build-lobehub-agents.mjs                 # writes web/lobehub/ (served at /lobehub/)
//   node scripts/build-lobehub-agents.mjs --out dist/lobehub
//   node scripts/build-lobehub-agents.mjs --check         # exit 1 if any skill fails to convert
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { frontmatter, zhPrompt } from '../bin/today.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
if (argv.includes('--help') || argv.includes('-h')) {
  console.log('Usage: node scripts/build-lobehub-agents.mjs [--out web/lobehub] [--check]');
  process.exit(0);
}
const oi = argv.indexOf('--out');
const OUT = resolve(root, oi !== -1 && argv[oi + 1] ? argv[oi + 1] : 'web/lobehub');
const check = argv.includes('--check');
const HOME = 'https://github.com/mohitagw15856/pm-claude-skills';

const catalogue = JSON.parse(readFileSync(join(root, 'web', 'skills.json'), 'utf8')).skills.filter((s) => !s.deprecated);
const byName = new Map(catalogue.map((s) => [s.name, s]));
// LobeHub market categories, matched to our bundles.
const CATEGORY = {
  'pm-china-work': 'office', 'pm-china-yearend': 'office', 'pm-essentials': 'office', 'pm-planning': 'office', 'pm-delivery': 'office',
  'pm-china-exams': 'education', 'pm-cv': 'career', 'pm-jobsearch': 'career', 'pm-career': 'career', 'pm-layoff': 'career',
  'pm-china-life': 'life', 'pm-renters': 'life', 'pm-personal': 'life', 'pm-decoders': 'life', 'pm-calculators': 'life',
  'pm-zh-content': 'copywriting', 'pm-gtm': 'copywriting', 'pm-chuhai': 'business', 'pm-china-compliance': 'business',
  'pm-engineering': 'programming', 'pm-data': 'programming', 'pm-cross': 'general',
};
const AVATAR = { office: '📝', education: '📚', career: '🎯', life: '🧭', copywriting: '✍️', business: '🌏', programming: '💻', general: '🧰' };

const dir = join(root, 'skills-i18n', 'zh');
const agents = [], problems = [];
for (const name of readdirSync(dir).sort()) {
  const f = join(dir, name, 'SKILL.md');
  if (!existsSync(f) || !byName.has(name)) continue;
  const { fm, body } = frontmatter(readFileSync(f, 'utf8'));
  // Drop the "translation of" note; keep the skill itself as the system role.
  const role = body.replace(/^\s*>\s*\[[^\n]*\n+/, '').trim();
  const title = ((role.match(/^# (.+)$/m) || [])[1] || '').replace(/技能$/, '').trim();
  const desc = (fm.description || '').replace(/^["']|["']$/g, '');
  if (!title || !role || !desc) { problems.push(`${name}: missing title, body or description`); continue; }
  const triggers = ((role.match(/##\s*示例触发语[^\n]*\n([\s\S]*?)(?=\n##\s|$)/) || [])[1] || '')
    .split('\n').map((l) => l.replace(/^[-*]\s*/, '').replace(/^[“"「]|[”"」]$/g, '').trim()).filter((l) => l && l.length <= 40).slice(0, 3);
  const questions = triggers.length ? triggers : [zhPrompt(desc) || `帮我用「${title}」处理一件事`].filter(Boolean);
  const plugin = byName.get(name).plugin;
  const category = CATEGORY[plugin] || 'general';
  const short = desc.split('。')[0].replace(/^为|^用/, (m) => m).slice(0, 90);
  const agent = {
    author: 'mohitagw15856',
    config: {
      systemRole: role,
      openingMessage: `你好！我是「${title}」助手，来自开源技能库 PM Skills。${questions[0] ? `你可以直接说：“${questions[0].replace(/[。！？]$/, '')}”，` : ''}缺什么信息我会先问你。`,
      openingQuestions: questions,
    },
    createdAt: (byName.get(name).updated || new Date().toISOString().slice(0, 10)),
    homepage: `${HOME}/blob/main/skills-i18n/zh/${name}/SKILL.md`,
    identifier: `pm-skills-${name}`,
    locale: 'zh-CN',
    meta: { avatar: AVATAR[category], tags: [plugin.replace(/^pm-/, ''), 'PM Skills', '职场'].slice(0, 5), title, description: short, category },
    schemaVersion: 1,
  };
  agents.push(agent);
}
if (check) {
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  console.log(`LobeHub export: ${agents.length} agents convert cleanly. ✓`);
  process.exit(0);
}
mkdirSync(OUT, { recursive: true });
for (const a of agents) writeFileSync(join(OUT, `${a.identifier}.zh-CN.json`), JSON.stringify(a, null, 2) + '\n');
writeFileSync(join(OUT, 'index.json'), JSON.stringify({
  _comment: 'PM Skills as LobeHub agents. Upload each file at app.lobehub.com (Discover / Market, submit an agent). Generated by scripts/build-lobehub-agents.mjs.',
  count: agents.length,
  agents: agents.map((a) => ({ identifier: a.identifier, title: a.meta.title, category: a.meta.category, file: `${a.identifier}.zh-CN.json` })),
}, null, 2) + '\n');
console.log(`Wrote ${agents.length} LobeHub agents to ${OUT.replace(`${root}/`, '')}/${problems.length ? ` (${problems.length} skipped: ${problems.join('; ')})` : ''}.`);
