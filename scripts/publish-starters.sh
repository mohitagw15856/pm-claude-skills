#!/usr/bin/env bash
# Publish each starters/<persona>/ folder as a GitHub template repository
# (pm-skills-starter-<persona>), creating it on first run and pushing updates
# after. Owner step: needs `gh auth login` with repo scope. Nothing here touches
# the library repository itself.
#
#   scripts/publish-starters.sh                 # all starters
#   scripts/publish-starters.sh product-manager # one
#   OWNER=someone scripts/publish-starters.sh   # publish under another account or org
set -euo pipefail
cd "$(dirname "$0")/.."
OWNER="${OWNER:-$(gh api user -q .login)}"
only="${1:-}"
for dir in starters/*/; do
  id="$(basename "$dir")"
  [ -n "$only" ] && [ "$only" != "$id" ] && continue
  repo="pm-skills-starter-$id"
  desc="PM Skills starter for a $(sed -n 's/^# \(.*\) starter (PM Skills)$/\1/p' "$dir/README.md"): team skill set, CI check and agent instructions, ready to clone."
  tmp="$(mktemp -d)"
  cp -R "$dir." "$tmp/"
  (
    cd "$tmp"
    git init -q -b main
    git add -A
    git -c user.name="pm-skills" -c user.email="noreply@github.com" commit -q -m "Starter template for $id (generated by scripts/build-starters.mjs)"
    if gh repo view "$OWNER/$repo" >/dev/null 2>&1; then
      git remote add origin "https://github.com/$OWNER/$repo.git"
      git push -q --force origin main
    else
      gh repo create "$OWNER/$repo" --public --description "$desc" --source . --remote origin --push >/dev/null
    fi
    gh repo edit "$OWNER/$repo" --template --homepage "https://mohitagw15856.github.io/pm-claude-skills/" >/dev/null
    echo "published https://github.com/$OWNER/$repo (template)"
  )
  rm -rf "$tmp"
done
