#!/usr/bin/env node
// Builds the system prompt for a single "PM Skills" agent on Chinese agent
// platforms (Coze 扣子, Alibaba Bailian 百炼, Baidu 文心智能体, Kimi), written
// to docs/listings/system-prompt-zh.md. The agent sees a compact index of the
// Simplified Chinese skills (title, name, one line, a trigger) and is told to
// pick one, ask for missing inputs and produce the finished document, then
// point to the full skill on Gitee for depth.
//
// Platforms cap the persona length, so the index is trimmed to --max-chars
// (default 7,500), keeping the China bundles first.
//
//   node scripts/build-listing-prompt.mjs [--max-chars 7500] [--check]
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { localSkill } from '../bin/today.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
if (argv.includes('--help') || argv.includes('-h')) {
  console.log('Usage: node scripts/build-listing-prompt.mjs [--max-chars 7500] [--check]');
  process.exit(0);
}
const mi = argv.indexOf('--max-chars');
const MAX = mi !== -1 ? Math.max(2000, +argv[mi + 1] || 7500) : 7500;
const OUT = join(root, 'docs', 'listings', 'system-prompt-zh.md');

const catalogue = JSON.parse(readFileSync(join(root, 'web', 'skills.json'), 'utf8')).skills.filter((s) => !s.deprecated);
const plugin = new Map(catalogue.map((s) => [s.name, s.plugin]));
const dir = join(root, 'skills-i18n', 'zh');
const PRIORITY = ['pm-china-work', 'pm-china-life', 'pm-china-exams', 'pm-china-compliance', 'pm-zh-content', 'pm-chuhai', 'pm-cv', 'pm-year-end'];
const rank = (n) => { const i = PRIORITY.indexOf(plugin.get(n)); return i === -1 ? PRIORITY.length : i; };
const skills = readdirSync(dir).filter((n) => plugin.has(n) && existsSync(join(dir, n, 'SKILL.md')))
  .map((n) => localSkill(root, 'zh', n)).filter(Boolean)
  .sort((a, b) => rank(a.name) - rank(b.name) || a.name.localeCompare(b.name));

const head = `你是“PM Skills 职场助手”，背后是开源技能库 PM Skills（${catalogue.length.toLocaleString('en-GB')} 个专业技能，MIT 协议，https://gitee.com/mohitagw/pm-claude-skills）。

## 你怎么工作
1. 先判断用户要完成什么事，从下面的技能清单里选**一个**最合适的技能，开头用一句话说明：“这件事我用「技能名」来做。”
2. 按这个技能的做法，先问清必须的信息（一次最多问三个问题）；用户说“直接写”时，用合理假设并标注出来。
3. 交付完整的成品（周报、申论、计划、清单、文案），不要只给建议。结构清楚，数字具体，能直接用。
4. 涉及劳动法、个税、社保医保、合规、医疗的内容，结尾加一句“以当地官方最新规定为准”，金额只做估算。
5. 清单里没有合适的技能时，照常回答，并说明可以在 Gitee 上搜索全部技能。
6. 结尾附上该技能完整版的链接：https://gitee.com/mohitagw/pm-claude-skills/blob/main/skills-i18n/zh/<技能名>/SKILL.md

## 技能清单（「中文名」技能名：做什么；用户可能这样说）
`;
const lines = [];
let used = head.length, dropped = 0;
for (const s of skills) {
  const one = s.summary.replace(/。$/, '').slice(0, 60);
  const line = `- 「${s.title.replace(/技能$/, '')}」${s.name}：${one}${s.prompt ? `；“${s.prompt}”` : ''}`;
  if (used + line.length + 1 > MAX) { dropped++; continue; }
  lines.push(line); used += line.length + 1;
}
const prompt = `${head}${lines.join('\n')}\n`;
const doc = `<!-- Generated by scripts/build-listing-prompt.mjs from skills-i18n/zh. Do not edit by hand; rerun the script. -->
# PM Skills 职场助手 · 系统提示词

用于扣子、阿里云百炼、文心智能体、Kimi 等平台的“人设与回复逻辑”或“系统提示词”。把下面代码块里的全部内容复制进去即可。上架步骤见 [README.md](README.md)。

收录 ${lines.length} 个中文技能${dropped ? `（为控制在 ${MAX} 字以内，省略了 ${dropped} 个）` : ''}，共 ${prompt.length} 字。

\`\`\`text
${prompt}\`\`\`
`;
if (argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== doc) { console.error('docs/listings/system-prompt-zh.md is out of date: run node scripts/build-listing-prompt.mjs'); process.exit(1); }
  console.log('docs/listings/system-prompt-zh.md is up to date. ✓');
  process.exit(0);
}
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, doc);
console.log(`Wrote docs/listings/system-prompt-zh.md: ${lines.length} skills, ${prompt.length} characters${dropped ? `, ${dropped} left out for length` : ''}.`);
