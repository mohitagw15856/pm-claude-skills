#!/usr/bin/env node
// Pinyin index for Chinese skill names, so people can search the way they type:
// "zb" or "zhoubao" finds 中文周报, "jj" finds 晋升答辩's neighbours, and so on.
//
// Writes web/zh-pinyin.json (committed; read by the playground, find.html and
// `npx pm-claude-skills find`): for each skill with a Chinese name (the H1 of
// skills-i18n/zh or zh-TW, else the lead of its data/zh-aliases.json entry),
// the toneless pinyin and the initials. Generating needs the pinyin-pro package,
// which is not a dependency: install it anywhere and pass PINYIN_MODULE_DIR.
//
//   PINYIN_MODULE_DIR=/tmp/py/node_modules node scripts/build-zh-pinyin.mjs
//   node scripts/build-zh-pinyin.mjs --check     # every Chinese-named skill is in the index (no pinyin-pro needed)
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { frontmatter } from '../bin/today.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
if (argv.includes('--help') || argv.includes('-h')) {
  console.log('Usage: PINYIN_MODULE_DIR=<node_modules with pinyin-pro> node scripts/build-zh-pinyin.mjs [--check]');
  process.exit(0);
}
const OUT = join(root, 'web', 'zh-pinyin.json');
const catalogue = JSON.parse(readFileSync(join(root, 'web', 'skills.json'), 'utf8')).skills.filter((s) => !s.deprecated);
const aliases = (() => { try { return JSON.parse(readFileSync(join(root, 'data', 'zh-aliases.json'), 'utf8')).aliases || {}; } catch { return {}; } })();

// Chinese names: translated title first, then the alias lead ("撰写产品需求文档（PRD）：…" → 撰写产品需求文档).
const names = {};
for (const s of catalogue) {
  const titles = [];
  for (const lang of ['zh', 'zh-TW']) {
    const f = join(root, 'skills-i18n', lang, s.name, 'SKILL.md');
    if (existsSync(f)) {
      const t = (frontmatter(readFileSync(f, 'utf8')).body.match(/^# (.+)$/m) || [])[1];
      if (t) titles.push(t.replace(/技能$/, '').trim());
    }
  }
  if (aliases[s.name]) titles.push(aliases[s.name].split(/[：:，,（(]/)[0].trim());
  const zh = [...new Set(titles.map((t) => t.replace(/[^一-鿿]/g, '')).filter((t) => t.length >= 2))];
  if (zh.length) names[s.name] = zh;
}

if (argv.includes('--check')) {
  const idx = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')).skills || {} : {};
  const missing = Object.keys(names).filter((n) => !idx[n] || idx[n].zh.join() !== names[n].join());
  if (missing.length) { console.error(`web/zh-pinyin.json is out of date for ${missing.length} skill(s): ${missing.slice(0, 8).join(', ')}. Regenerate with PINYIN_MODULE_DIR=… node scripts/build-zh-pinyin.mjs`); process.exit(1); }
  console.log(`web/zh-pinyin.json covers all ${Object.keys(names).length} Chinese-named skills. ✓`);
  process.exit(0);
}

let pinyin;
try { pinyin = (await import('pinyin-pro')).pinyin; } catch {
  const dir = process.env.PINYIN_MODULE_DIR;
  if (!dir) { console.error('Needs pinyin-pro: npm i --prefix /tmp/py pinyin-pro, then PINYIN_MODULE_DIR=/tmp/py/node_modules'); process.exit(1); }
  pinyin = createRequire(join(resolve(dir), 'noop.js'))('pinyin-pro').pinyin;
}
const skills = {};
for (const [name, zh] of Object.entries(names).sort()) {
  const py = zh.map((t) => pinyin(t, { toneType: 'none', type: 'array' }).map((x) => x.replace(/ü/g, 'v')));
  skills[name] = { zh, full: py.map((a) => a.join('')), initials: py.map((a) => a.map((x) => x[0]).join('')) };
}
writeFileSync(OUT, JSON.stringify({ _comment: 'Toneless pinyin and initials of each skill\'s Chinese name, for pinyin search. Generated by scripts/build-zh-pinyin.mjs.', skills }) + '\n');
console.log(`Wrote web/zh-pinyin.json: ${Object.keys(skills).length} skills.`);
