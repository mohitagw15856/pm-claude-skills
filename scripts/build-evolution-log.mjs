#!/usr/bin/env node
// The public evolution log: every machine rewrite of a skill (data/evolution-log.json,
// appended by scripts/lib/evolution-log.mjs) rendered as EVOLUTION.md, plus
// web/evolution-log.json for web/evolution.html (built at deploy).
//
//   node scripts/build-evolution-log.mjs           # write EVOLUTION.md and the web data
//   node scripts/build-evolution-log.mjs --check   # fail if EVOLUTION.md is stale or an entry is malformed
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = 'https://github.com/mohitagw15856/pm-claude-skills';
const { entries = [] } = JSON.parse(readFileSync(join(root, 'data', 'evolution-log.json'), 'utf8'));
const NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const LOOPS = { 'self-improve': 'Self-improve', evolve: 'Evolve (blind champion vs challenger)', improve: 'Improve (critique and rewrite)' };

const problems = entries.flatMap((e, i) => [
  !/^\d{4}-\d{2}-\d{2}$/.test(e.date || '') && `entry ${i}: bad date`,
  !NAME.test(e.skill || '') && `entry ${i}: bad skill name`,
  !LOOPS[e.loop] && `entry ${i}: unknown loop "${e.loop}"`,
  typeof e.kept !== 'boolean' && `entry ${i}: kept must be true or false`,
].filter(Boolean));

const sorted = [...entries].sort((a, b) => b.date.localeCompare(a.date) || a.skill.localeCompare(b.skill));
const kept = sorted.filter((e) => e.kept);
const gains = kept.filter((e) => e.before != null && e.after != null).map((e) => e.after - e.before);
const stats = {
  attempts: sorted.length, kept: kept.length, rejected: sorted.length - kept.length,
  skills: new Set(sorted.map((e) => e.skill)).size,
  avgGain: gains.length ? Math.round((gains.reduce((a, b) => a + b, 0) / gains.length) * 100) / 100 : null,
};
const f = (x) => (x == null ? 'n/a' : x.toFixed(2));
const link = (e) => (e.pr ? `[#${e.pr}](${REPO}/pull/${e.pr})` : e.run ? `[run](${REPO}/actions/runs/${e.run})` : '');

const md = [
  '# Evolution log',
  '',
  '<!-- Generated by scripts/build-evolution-log.mjs from data/evolution-log.json; do not edit by hand. -->',
  '',
  'This library rewrites its own weakest skills. A model proposes a rewrite, a judge scores it against the original, and only a clear win is kept. A person still reviews the pull request before anything merges. Every attempt is recorded here, **including the ones that lost**, so the claim "the skills improve themselves" can be checked line by line.',
  '',
  `**${stats.attempts} attempt${stats.attempts === 1 ? '' : 's'}** on ${stats.skills} skill${stats.skills === 1 ? '' : 's'}: ${stats.kept} kept, ${stats.rejected} rejected${stats.avgGain != null ? `, average gain when kept +${stats.avgGain.toFixed(2)} (1–5 rubric)` : ''}. [Browse it on the site](https://mohitagw15856.github.io/pm-claude-skills/evolution.html).`,
  '',
  'The loops: ' + Object.entries(LOOPS).map(([k, v]) => `\`${k}\`, ${v}`).join('; ') + '. They run when the maintainer dispatches them; the evolve loop also runs monthly once the repository variable `EVOLVE_MONTHLY` is set to `true`.',
  '',
  '| Date | Skill | Loop | Before | After | Result | Link |',
  '|---|---|---|---|---|---|---|',
  ...sorted.map((e) => `| ${e.date} | [${e.skill}](skills/${e.skill}/SKILL.md) | ${e.loop} | ${f(e.before)} | ${f(e.after)} | ${e.kept ? '✅ kept' : '🛡 original held'} | ${link(e)} |`),
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const cur = existsSync(join(root, 'EVOLUTION.md')) ? readFileSync(join(root, 'EVOLUTION.md'), 'utf8') : '';
  if (problems.length) { console.error(`Evolution log: ${problems.join('; ')}`); process.exit(1); }
  if (cur !== md) { console.error('EVOLUTION.md is out of date. Run node scripts/build-evolution-log.mjs'); process.exit(1); }
  console.log(`Evolution log up to date: ${stats.attempts} attempts, ${stats.kept} kept. ✓`);
  process.exit(0);
}
if (problems.length) console.warn(`Evolution log warnings: ${problems.join('; ')}`);
writeFileSync(join(root, 'EVOLUTION.md'), md);
writeFileSync(join(root, 'web', 'evolution-log.json'), JSON.stringify({ generated: new Date().toISOString().slice(0, 10), stats, loops: LOOPS, entries: sorted }, null, 2) + '\n');
console.log(`Wrote EVOLUTION.md and web/evolution-log.json: ${stats.attempts} attempts, ${stats.kept} kept.`);
