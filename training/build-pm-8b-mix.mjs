#!/usr/bin/env node
// PM-8B: the training mix and the held-out test set.
//
//   node training/build-pm-8b-mix.mjs
//     → training/pm-8b-train.jsonl         routing + structure (sft.jsonl), teacher
//                                          completions (teacher.jsonl, if built) and the
//                                          reviewed samples, minus every held-out skill
//     → training/pm-8b-heldout-tasks.json  SkillBench-format tasks for skills the model
//                                          never sees in training, so the evaluation is fair
//
// The split (training/pm-8b-split.mjs) is deterministic, so it is the same on every
// machine and every rebuild: about 10% of the skills with eval cases are held out.
// Evaluate a trained model on it with the SkillBench runner, e.g. served by Ollama:
//   LOCAL_API_KEY=x node skillbench/run-skillbench.mjs --models local:pm-8b,local:qwen3:8b \
//     --tasks training/pm-8b-heldout-tasks.json --out training/pm-8b-results.json
// The "bare" score is the one that matters: the skill's judgment without the skill.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { heldOut } from './pm-8b-split.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const readJsonl = (p) => (existsSync(p) ? readFileSync(p, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)) : []);
const cases = JSON.parse(readFileSync(join(root, 'evals', 'cases.json'), 'utf8')).cases;
const index = JSON.parse(readFileSync(join(root, 'web', 'skills-index.json'), 'utf8')).skills || [];
const plugin = Object.fromEntries(index.map((s) => [s.name, s.plugin || 'other']));

// Which skill a training row is about, so held-out skills can be removed from it.
const skillOfRow = (r) => r.skill || r.meta?.skill || ((r.messages || []).find((m) => m.role === 'assistant')?.content.match(/^\*\*([a-z0-9-]+)\*\*/) || [])[1];

const train = [];
let dropped = 0;
const sources = { 'training/sft.jsonl': 0, 'training/teacher.jsonl': 0, 'dataset/samples.jsonl': 0 };
// sft.jsonl rows are short (a skill's name and a summary, median ~460 characters). As
// most of the mix they taught the model to answer briefly: the first trained adapter
// (2026-10-16) scored 2.53 without a skill against 4.69 for its base model. So once
// full-depth rows exist, the short rows are capped at a fifth of them, picked evenly.
const fullDepth = ['training/teacher.jsonl', 'dataset/samples.jsonl'].reduce((n, p) => n + readJsonl(join(root, p)).length, 0);
// "structure" rows pair a real task with a description of the skill instead of the
// work ("I'll approach this with the X discipline. Structure: ..."). Because their
// prompts look like real requests, even 21 of them taught the model to describe
// instead of do (full run, 2026-10-17: bare 2.35 against the base's 4.69). Only the
// routing rows, whose prompts are plainly different, stay.
const sftAll = readJsonl(join(root, 'training/sft.jsonl')).filter((r) => r.track !== 'structure');
const sftCap = fullDepth >= 50 ? Math.min(sftAll.length, Math.round(fullDepth * 0.2)) : sftAll.length;
const sftKeep = new Set(Array.from({ length: sftCap }, (_, i) => Math.floor((i * sftAll.length) / sftCap)));
for (const src of Object.keys(sources)) {
  const rows = src === 'training/sft.jsonl' ? sftAll.filter((_, i) => sftKeep.has(i)) : readJsonl(join(root, src));
  for (const r of rows) {
    const messages = r.messages || (r.system && r.user && r.assistant ? [{ role: 'system', content: r.system }, { role: 'user', content: r.user }, { role: 'assistant', content: r.assistant }] : null);
    if (!messages) continue;
    const skill = skillOfRow(r);
    if (skill && heldOut(skill)) { dropped++; continue; }
    train.push(JSON.stringify({ messages }));
    sources[src]++;
  }
}

const held = [...new Set(cases.map((c) => c.skill))].filter(heldOut).sort();
const tasks = cases.filter((c) => held.includes(c.skill)).map((c, i) => ({ id: `${c.skill}-${i}`, domain: plugin[c.skill] || 'other', skill: c.skill, input: c.input }));
writeFileSync(join(here, 'pm-8b-train.jsonl'), train.join('\n') + '\n');
writeFileSync(join(here, 'pm-8b-heldout-tasks.json'), JSON.stringify({ version: 'pm-8b-heldout-1', _comment: 'Generated by training/build-pm-8b-mix.mjs. Skills here are never in pm-8b-train.jsonl.', tasks }, null, 2) + '\n');
console.log(`PM-8B mix: ${train.length} training rows (${Object.entries(sources).map(([k, v]) => `${v} from ${k}`).join(', ')}), ${dropped} held-out rows removed; ${tasks.length} held-out tasks across ${held.length} skills.`);
if (!sources['training/teacher.jsonl']) console.log('No teacher completions yet: run training/teacher-pass.mjs first for the full-depth rows (see training/README.md).');
