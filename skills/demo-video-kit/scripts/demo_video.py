#!/usr/bin/env python3
"""Turn a shot list into captions and the ffmpeg commands that assemble a demo video.

The script does the arithmetic and the quoting; it never runs ffmpeg itself. It
writes three files into the output folder: captions.srt (timed to the assembled
video), concat.txt (the clip list) and build.sh (the commands, in order).

Shot list (JSON array). Times are seconds within each source recording:

  [{"file": "recording.mov", "start": 12, "end": 20,
    "caption": "Create a project in one click"},
   {"file": "recording.mov", "start": 45.5, "end": 58, "caption": "Invite the team"}]

Example:
  python3 demo_video.py plan shots.json --out build --size 1920x1080
  python3 demo_video.py check shots.json
"""
import argparse
import json
import math
import re
import shlex
import sys
from pathlib import Path

SIZE_RE = re.compile(r"^(\d{2,5})x(\d{2,5})$")


def load_shots(path):
    """Read and validate the shot list. Raises ValueError with a usable message."""
    try:
        raw = json.loads(Path(path).read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ValueError(f"shot list is not valid JSON: {exc}") from exc
    if not isinstance(raw, list) or not raw:
        raise ValueError("shot list must be a non-empty JSON array")
    shots = []
    for i, item in enumerate(raw, start=1):
        if not isinstance(item, dict):
            raise ValueError(f"shot {i}: must be an object")
        name = item.get("file")
        if not isinstance(name, str) or not name.strip():
            raise ValueError(f"shot {i}: 'file' is required")
        if "\n" in name or "\r" in name:
            raise ValueError(f"shot {i}: 'file' must be a single line")
        times = []
        for key in ("start", "end"):
            value = item.get(key)
            if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
                raise ValueError(f"shot {i}: '{key}' must be a finite number of seconds")
            times.append(float(value))
        start, end = times
        if start < 0:
            raise ValueError(f"shot {i}: 'start' cannot be negative")
        if end <= start:
            raise ValueError(f"shot {i}: 'end' must be after 'start'")
        caption = item.get("caption", "")
        if not isinstance(caption, str):
            raise ValueError(f"shot {i}: 'caption' must be text")
        if name.startswith("-"):
            name = "./" + name          # never let a file name be read as an ffmpeg option
        shots.append({"file": name, "start": start, "end": end,
                      "caption": " ".join(caption.split())})
    return shots


def timestamp(seconds):
    """Seconds to an SRT timestamp, HH:MM:SS,mmm."""
    millis = int(round(seconds * 1000))
    hours, millis = divmod(millis, 3600000)
    minutes, millis = divmod(millis, 60000)
    secs, millis = divmod(millis, 1000)
    return f"{hours:02d}:{minutes:02d}:{secs:02d},{millis:03d}"


def build_srt(shots):
    """Captions placed on the assembled timeline: each shot starts where the last ended."""
    blocks, cursor, number = [], 0.0, 0
    for shot in shots:
        length = shot["end"] - shot["start"]
        if shot["caption"]:
            number += 1
            blocks.append(f"{number}\n{timestamp(cursor)} --> {timestamp(cursor + length)}\n{shot['caption']}\n")
        cursor += length
    return "\n".join(blocks), cursor


def build_commands(shots, width, height, fps):
    """The ffmpeg commands, one per line, with every file name shell-quoted."""
    scale = (f"scale={width}:{height}:force_original_aspect_ratio=decrease,"
             f"pad={width}:{height}:(ow-iw)/2:(oh-ih)/2,fps={fps}")
    lines = ["#!/bin/sh", "# Generated by demo_video.py. Read it before you run it.", "set -eu"]
    for i, shot in enumerate(shots, start=1):
        lines.append(
            "ffmpeg -y -ss {s:.3f} -to {e:.3f} -i {src} -vf {vf} -c:v libx264 -pix_fmt yuv420p "
            "-c:a aac -ar 48000 {out}".format(
                s=shot["start"], e=shot["end"], src=shlex.quote(shot["file"]),
                vf=shlex.quote(scale), out=shlex.quote(f"clip_{i:02d}.mp4")))
    lines.append("ffmpeg -y -f concat -safe 0 -i concat.txt -c copy joined.mp4")
    lines.append("ffmpeg -y -i joined.mp4 -vf subtitles=captions.srt -c:a copy final.mp4")
    return "\n".join(lines) + "\n"


def parse_size(text):
    match = SIZE_RE.match(text)
    if not match:
        raise ValueError("size must look like 1920x1080")
    width, height = int(match.group(1)), int(match.group(2))
    if width % 2 or height % 2:
        raise ValueError("width and height must be even numbers for H.264")
    return width, height


def main(argv=None):
    parser = argparse.ArgumentParser(description="Plan a demo video from a shot list.")
    sub = parser.add_subparsers(dest="cmd", required=True)
    plan = sub.add_parser("plan", help="write captions.srt, concat.txt and build.sh")
    plan.add_argument("shots", help="path to the shot list JSON")
    plan.add_argument("--out", default="build", help="output folder (default: build)")
    plan.add_argument("--size", default="1920x1080", help="frame size, for example 1920x1080 or 1080x1920")
    plan.add_argument("--fps", type=int, default=30, help="frames per second (default: 30)")
    check = sub.add_parser("check", help="validate the shot list and print the running order")
    check.add_argument("shots", help="path to the shot list JSON")
    args = parser.parse_args(argv)

    try:
        shots = load_shots(args.shots)
        if args.cmd == "check":
            _, total = build_srt(shots)
            for i, shot in enumerate(shots, start=1):
                print(f"{i:>2}. {shot['end'] - shot['start']:6.1f}s  {shot['file']}  {shot['caption']}")
            print(f"{len(shots)} shots, {total:.1f}s total")
            return 0
        width, height = parse_size(args.size)
        if not 1 <= args.fps <= 120:
            raise ValueError("fps must be between 1 and 120")
        srt, total = build_srt(shots)
        out = Path(args.out)
        out.mkdir(parents=True, exist_ok=True)
        (out / "captions.srt").write_text(srt, encoding="utf-8")
        (out / "concat.txt").write_text(
            "".join(f"file 'clip_{i:02d}.mp4'\n" for i in range(1, len(shots) + 1)), encoding="utf-8")
        (out / "build.sh").write_text(build_commands(shots, width, height, args.fps), encoding="utf-8")
    except (ValueError, OSError) as exc:
        parser.error(str(exc))
    print(f"wrote {out}/captions.srt, concat.txt, build.sh: {len(shots)} shots, {total:.1f}s total, {width}x{height}@{args.fps}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
